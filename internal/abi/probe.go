// cLayout is the ABI as reported by the C compiler.
type cLayout struct {
	structs map[string]cStruct
	enums   map[string]uint64
}

type cStruct struct {
	size   uint64
	align  uint64
	fields map[string]cField
}

type cField struct {
	offset uint64
	size   uint64
}

// findCC returns the first available C compiler, or "" if none is on PATH.
func findCC() string {
	if cc := os.Getenv("CC"); cc != "" {
		if path, err := exec.LookPath(cc); err == nil {
			return path
		}
	}
	for _, name := range []string{"cc", "gcc", "clang"} {
		if path, err := exec.LookPath(name); err == nil {
			return path
		}
	}
	return ""
}

// repoRoot walks up from the working directory to the module root.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod found above %s", dir)
		}
		dir = parent
	}
}

// cSource renders the probe program for a group, omitting any enumerant named
// in skip.
//
// Field sizes use sizeof(((T *)0)->field), which never dereferences the null
// pointer: sizeof does not evaluate its operand.
func (g Group) cSource(skip map[string]bool) string {
	var b strings.Builder

	b.WriteString("/* Generated by internal/abi. Reports the Vulkan C ABI. */\n")
	b.WriteString("#include <stdio.h>\n")
	b.WriteString("#include <stddef.h>\n")
	// Provisional extensions (the AMDX ones, at the time of writing) are real
	// API, just gated behind this macro in the headers.
	b.WriteString("#define VK_ENABLE_BETA_EXTENSIONS 1\n")
	if g.Macro != "" {
		// Platform structs only exist once their VK_USE_PLATFORM_* macro is set,
		// and that path goes through vulkan.h rather than vulkan_core.h.
		fmt.Fprintf(&b, "#define %s 1\n", g.Macro)
		b.WriteString("#include <vulkan/vulkan.h>\n")
	} else {
		b.WriteString("#include <vulkan/vulkan_core.h>\n")
	}
	b.WriteString("\nint main(void) {\n")

	for _, s := range g.Structs {
		fmt.Fprintf(&b, "\tprintf(\"s|%s|%%zu|%%zu\\n\", sizeof(%s), _Alignof(%s));\n",
			s.CName, s.CName, s.CName)
		for _, cField := range s.CFields {
			if cField == "" {
				continue // synthetic Go field: padding or a bitfield pack
			}
			fmt.Fprintf(&b,
				"\tprintf(\"f|%s|%s|%%zu|%%zu\\n\", offsetof(%s, %s), sizeof(((%s *)0)->%s));\n",
				s.CName, cField, s.CName, cField, s.CName, cField)
		}
	}

	for _, e := range g.Enums {
		if skip[e.CName] {
			continue
		}
		// Cast through long long first so that negative enumerants sign-extend,
		// matching how V widens the Go side.
		fmt.Fprintf(&b, "\tprintf(\"e|%s|%%llu\\n\", (unsigned long long)(long long)(%s));\n",
			e.CName, e.CName)
	}

	b.WriteString("\treturn 0;\n}\n")
	return b.String()
}

// maxProbeAttempts bounds the compile/retry loop. Both gcc and clang report
// every distinct undeclared identifier in a single pass, so the second attempt
// normally succeeds.
const maxProbeAttempts = 4

// probe compiles and runs the group's probe program and parses its report.
//
// Enumerants the generator declares in Go but the headers do not define are
// removed and returned in absent rather than failing the build: there is no C
// value to compare them against. Any other compile error is returned as such,
// carrying the compiler's diagnostics, which name the offending struct or
// member directly.
func probe(cc, includeDir, tmpDir string, g Group) (layout *cLayout, absent []string, err error) {
	srcPath := filepath.Join(tmpDir, "probe_"+g.Name+".c")
	// Name the executable explicitly rather than letting the compiler decide:
	// MinGW appends .exe to an extensionless -o, and exec would then not find
	// the path we asked for.
	binPath := filepath.Join(tmpDir, "probe_"+g.Name)
	if runtime.GOOS == "windows" {
		binPath += ".exe"
	}

	declared := make(map[string]bool, len(g.Enums))
	for _, e := range g.Enums {
		declared[e.CName] = true
	}
	skip := map[string]bool{}

	for attempt := 0; attempt < maxProbeAttempts; attempt++ {
		if err := os.WriteFile(srcPath, []byte(g.cSource(skip)), 0o644); err != nil {
			return nil, nil, err
		}

		build := exec.Command(cc, "-std=gnu11", "-I", includeDir, "-o", binPath, srcPath)
		// Normalise diagnostics so undeclaredIdentifiers can read them.
		build.Env = append(os.Environ(), "LC_ALL=C")

		out, buildErr := build.CombinedOutput()
		if buildErr == nil {
			report, err := runProbe(binPath)
			if err != nil {
				return nil, nil, err
			}
			return report, absent, nil
		}

		// Only enumerants are allowed to go missing. A missing struct or member
		// is a defect in the bindings, so surface the compiler error instead.
		names := undeclaredIdentifiers(string(out))
		progressed := false
		for _, name := range names {
			if declared[name] && !skip[name] {
				skip[name] = true
				absent = append(absent, name)
				progressed = true
			}
		}
		if !progressed {
			return nil, nil, fmt.Errorf("compiling probe: %w\n%s", buildErr, out)
		}
	}

	return nil, nil, fmt.Errorf("probe still failing to compile after %d attempts", maxProbeAttempts)
}

func runProbe(binPath string) (*cLayout, error) {
	out, err := exec.Command(binPath).Output()
	if err != nil {
		return nil, fmt.Errorf("running probe: %w", err)
	}
	return parseReport(string(out))
}

// undeclaredRE matches both gcc's "'NAME' undeclared" and clang's
// "use of undeclared identifier 'NAME'". Either compiler may quote with ASCII
// apostrophes or typographic quotes depending on locale.
var undeclaredRE = regexp.MustCompile(
	`(?:use of undeclared identifier\s+['\x{2018}]([A-Za-z_][A-Za-z0-9_]*)['\x{2019}]` +
		`|['\x{2018}]([A-Za-z_][A-Za-z0-9_]*)['\x{2019}]\s+undeclared)`)

// undeclaredIdentifiers extracts the identifiers a compiler reported as
// undeclared, deduplicated and in first-seen order.
func undeclaredIdentifiers(diagnostics string) []string {
	var names []string
	seen := map[string]bool{}

	for _, m := range undeclaredRE.FindAllStringSubmatch(diagnostics, -1) {
		name := m[1]
		if name == "" {
			name = m[2]
		}
		if name == "" || seen[name] {
			continue
		}
		seen[name] = true
		names = append(names, name)
	}

	return names
}

func parseReport(out string) (*cLayout, error) {
	layout := &cLayout{
		structs: make(map[string]cStruct),
		enums:   make(map[string]uint64),
	}

	for _, line := range strings.Split(out, "\n") {
		// The probe's stdio writes CRLF on Windows, which would otherwise end
		// up inside the last field of every record.
		line = strings.TrimRight(line, "\r")
		if line == "" {
			continue
		}
		parts := strings.Split(line, "|")
		switch parts[0] {
		case "s":
			if len(parts) != 4 {
				return nil, fmt.Errorf("malformed struct record %q", line)
			}
			size, err := strconv.ParseUint(parts[2], 10, 64)
			if err != nil {
				return nil, fmt.Errorf("struct record %q: %w", line, err)
			}
			align, err := strconv.ParseUint(parts[3], 10, 64)
			if err != nil {
				return nil, fmt.Errorf("struct record %q: %w", line, err)
			}
			layout.structs[parts[1]] = cStruct{
				size:   size,
				align:  align,
				fields: make(map[string]cField),
			}
		case "f":
			if len(parts) != 5 {
				return nil, fmt.Errorf("malformed field record %q", line)
			}
			s, ok := layout.structs[parts[1]]
			if !ok {
				return nil, fmt.Errorf("field record %q precedes its struct record", line)
			}
			offset, err := strconv.ParseUint(parts[3], 10, 64)
			if err != nil {
				return nil, fmt.Errorf("field record %q: %w", line, err)
			}
			size, err := strconv.ParseUint(parts[4], 10, 64)
			if err != nil {
				return nil, fmt.Errorf("field record %q: %w", line, err)
			}
			s.fields[parts[2]] = cField{offset: offset, size: size}
		case "e":
			if len(parts) != 3 {
				return nil, fmt.Errorf("malformed enum record %q", line)
			}
			value, err := strconv.ParseUint(parts[2], 10, 64)
			if err != nil {
				return nil, fmt.Errorf("enum record %q: %w", line, err)
			}
			layout.enums[parts[1]] = value
		default:
			return nil, fmt.Errorf("unrecognised record %q", line)
		}
	}

	return layout, nil
}
